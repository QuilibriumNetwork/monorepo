//! System DNS resolver config for the swarm's DNS transport.
//!
//! libp2p's `with_dns()` reads the system resolver config once and fails
//! the whole swarm when it lists no nameservers. At boot a host's
//! `/etc/resolv.conf` can still be empty when the node starts (DHCP or
//! the network manager writes it a few seconds later), so the node
//! exited before its first frame. Here the config gets a bounded wait;
//! if it never becomes usable, the swarm starts with an empty resolver:
//! `/ip4` and `/ip6` peers (the bootstrap peers among them) still dial,
//! `/dns` addresses fail to resolve until a restart. No lookup ever goes
//! to a resolver the operator did not configure.

use std::time::Duration;

use libp2p::dns::{ResolveError, ResolverConfig, ResolverOpts};
use tokio::time::Instant;
use tracing::{info, warn};

/// How long start waits for the system resolver config to list a
/// nameserver. A boot-time race ends within seconds (5 s seen on a
/// regular node); the cap bounds the delay when a host has none at all.
/// Workers wait too: a worker started on its own host (cluster layout)
/// meets the same boot race as a master.
const DNS_CONFIG_WAIT: Duration = Duration::from_secs(30);

/// Re-read interval while waiting.
const DNS_CONFIG_POLL: Duration = Duration::from_secs(1);

/// A resolver config reader.
pub(crate) type DnsConfigRead = fn() -> Result<(ResolverConfig, ResolverOpts), ResolveError>;

/// Where `P2PNode::start` gets its resolver config, and how long it waits.
#[derive(Clone, Copy)]
pub(crate) struct DnsSource {
    pub(crate) read: DnsConfigRead,
    pub(crate) wait: Duration,
    pub(crate) poll: Duration,
}

impl DnsSource {
    /// The system resolver config (`/etc/resolv.conf` on Unix).
    pub(crate) fn system() -> Self {
        Self {
            read: hickory_resolver::system_conf::read_system_conf,
            wait: DNS_CONFIG_WAIT,
            poll: DNS_CONFIG_POLL,
        }
    }

    /// Returns the config the DNS transport should use; see
    /// [`system_dns_config`].
    pub(crate) async fn config(self) -> (ResolverConfig, ResolverOpts) {
        system_dns_config(self.read, self.wait, self.poll).await
    }
}

/// Returns the resolver config the DNS transport should use.
///
/// Calls `read` until it succeeds or `wait` has passed, `poll` apart.
/// After the wait it returns an empty config (no nameservers): the swarm
/// starts and only name resolution is unavailable. Logs at most two
/// lines: one warn when the first read fails, then one info when the
/// config appears or one warn when the node gives up waiting.
pub(crate) async fn system_dns_config<F>(
    mut read: F,
    wait: Duration,
    poll: Duration,
) -> (ResolverConfig, ResolverOpts)
where
    F: FnMut() -> Result<(ResolverConfig, ResolverOpts), ResolveError>,
{
    let started = Instant::now();
    let mut attempts: u32 = 0;
    loop {
        attempts += 1;
        let err = match read() {
            Ok(config) => {
                if attempts > 1 {
                    info!(
                        waited_ms = started.elapsed().as_millis() as u64,
                        attempts, "p2p: system DNS resolver config ready; DNS transport enabled"
                    );
                }
                return config;
            }
            Err(e) => e,
        };
        if attempts == 1 {
            warn!(
                error = %err,
                wait_s = wait.as_secs(),
                "p2p: system DNS resolver config unusable; waiting for /etc/resolv.conf \
                 to list a nameserver before starting the swarm"
            );
        }
        if started.elapsed() >= wait {
            warn!(
                error = %err,
                waited_ms = started.elapsed().as_millis() as u64,
                attempts,
                "p2p: starting without DNS resolution: /ip4 and /ip6 peers dial, /dns peer \
                 addresses fail until the node restarts with a nameserver in /etc/resolv.conf"
            );
            return (ResolverConfig::new(), ResolverOpts::default());
        }
        tokio::time::sleep(poll).await;
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use hickory_resolver::system_conf::parse_resolv_conf;

    /// What a host writes before DHCP has supplied a nameserver.
    const NO_NAMESERVER: &str = "# Generated by resolvconf\nsearch lan\n";
    /// A documentation-range resolver (RFC 5737).
    const ONE_NAMESERVER: &str = "nameserver 192.0.2.53\n";

    /// Long enough that a descheduled test thread still reads twice.
    const WAIT: Duration = Duration::from_millis(500);
    const POLL: Duration = Duration::from_millis(10);

    /// The base failure: a resolver config with no nameservers made the
    /// swarm builder fail and the node exit. It must now yield an empty
    /// config after a bounded number of reads.
    #[tokio::test]
    async fn starts_without_dns_when_resolv_conf_lists_no_nameservers() {
        // The base error text, from the same parser the system read uses.
        let base_err = parse_resolv_conf(NO_NAMESERVER).unwrap_err().to_string();
        assert!(
            base_err.contains("no nameservers found in config"),
            "unexpected parser error: {base_err}"
        );

        let mut reads = 0u32;
        let started = std::time::Instant::now();
        let (cfg, _opts) = system_dns_config(
            || {
                reads += 1;
                parse_resolv_conf(NO_NAMESERVER)
            },
            WAIT,
            POLL,
        )
        .await;

        assert!(
            cfg.name_servers().is_empty(),
            "fallback must not add a resolver"
        );
        assert!(reads >= 2, "the config was read once only: {reads} reads");
        assert!(
            started.elapsed() < Duration::from_secs(5),
            "the wait overran its cap: {:?}",
            started.elapsed()
        );
    }

    /// The boot race: the nameserver appears while start waits, so the
    /// DNS transport gets the system resolver, not the empty fallback.
    #[tokio::test]
    async fn uses_the_nameserver_that_appears_while_waiting() {
        let mut reads = 0u32;
        let (cfg, _opts) = system_dns_config(
            || {
                reads += 1;
                if reads < 3 {
                    parse_resolv_conf(NO_NAMESERVER)
                } else {
                    parse_resolv_conf(ONE_NAMESERVER)
                }
            },
            Duration::from_secs(10),
            POLL,
        )
        .await;

        assert!(reads > 1, "the config was read once only: {reads} reads");
        assert_eq!(reads, 3, "reads continued past the first usable config");
        let addrs: Vec<String> = cfg
            .name_servers()
            .iter()
            .map(|ns| ns.socket_addr.to_string())
            .collect();
        assert!(
            addrs.iter().any(|a| a == "192.0.2.53:53"),
            "system nameserver lost: {addrs:?}"
        );
    }

    /// The node path: `P2PNode::start` with a resolver config that lists
    /// no nameserver returns a running swarm instead of the base's
    /// `dns: no nameservers found in config` error.
    #[tokio::test]
    async fn p2p_start_survives_a_resolv_conf_with_no_nameserver() {
        let config = quil_config::P2PConfig {
            network: 99,
            bootstrap_peers: Vec::new(),
            direct_peers: Vec::new(),
            ..Default::default()
        };
        let node = crate::P2PNode::new_with_options(&config, true, None)
            .unwrap()
            .with_dns_source(DnsSource {
                read: || parse_resolv_conf(NO_NAMESERVER),
                wait: WAIT,
                poll: POLL,
            });
        let mut sup = quil_lifecycle::Supervisor::<anyhow::Error>::new();
        if let Err(e) = node.start(&mut sup, "/ip4/127.0.0.1/tcp/0").await {
            panic!("p2p start failed on a resolv.conf with no nameserver: {e}");
        }
    }
}
